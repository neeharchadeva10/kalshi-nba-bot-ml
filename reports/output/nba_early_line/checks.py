"""Research log #58 multi-source data checks.  DISCOVERY dates only (2025-10-21..2026-01-22); writes CHECKS.md and checks.json.
Run: .venv/Scripts/python.exe reports/output/nba_early_line/checks.py"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import el_lib as E  # noqa: E402


def main():
    uni, uinfo = E.load_universe(E.DISC_FIRST, E.DISC_LAST)
    out = {"dates": [E.DISC_FIRST, E.DISC_LAST], "universe": {"games": int(len(uni)), **{k: v for k, v in uinfo.items()}}}
    # --- T / date consistency (price-side metadata only)
    et = uni["T"].map(E.C44.et_date)
    out["universe"]["T_events_list_differs_from_42"] = int((uni["T"] != uni.T_events_list).sum())
    out["universe"]["ET_date_of_T_differs_from_event_date"] = [[r.event, r.date, d] for r, d in zip(uni.itertuples(), et) if d != r.date]
    # --- 1. T-4h L_e: 1-minute table vs hourly table
    hdf = E.hourly_check(uni, 4)
    hsum, excl = E.hourly_summary(hdf)
    out["T-4h_1m_vs_hourly"] = hsum
    keep = uni[~uni.event.isin(excl)].reset_index(drop=True)
    # --- 2. finals: hoopR vs Kalshi vs odds-API file (analysis sample = after exclusions)
    hf = E.finals_hoopr(keep.hoopr_id)
    kf = E.finals_kalshi(keep.event)
    fin = pd.DataFrame({"event": keep.event.values, "hoopr": hf.values.astype(float), "kalshi": kf.reindex(keep.event).values.astype(float)})
    both = fin.dropna()
    diff = both[(both.hoopr != both.kalshi)]
    out["finals"] = {"games": int(len(fin)), "hoopr_missing": int(fin.hoopr.isna().sum()), "kalshi_missing": int(fin.kalshi.isna().sum()),
                     "both": int(len(both)), "equal": int((both.hoopr == both.kalshi).sum()), "differ": int(len(diff)),
                     "differ_list": [{"event": r.event, "hoopr": r.hoopr, "kalshi": r.kalshi} for r in diff.itertuples()],
                     "max_abs_diff": float((both.hoopr - both.kalshi).abs().max()) if len(both) else None,
                     "odds_api_close_file": E.odds_file_status()}
    out["finals"]["kalshi_settlement_bracket_vs_hoopr"] = E.bracket_consistency(
        list(keep.event), dict(zip(fin.event, fin.hoopr)))
    out["finals"]["odds_api_close_file"]["verdict"] = ("scores present" if out["finals"]["odds_api_close_file"]["has_scores"]
                                                       else "no scores in that file")
    # --- 3. F56 reproduction
    out["F56_reproduction_vs_56"] = E.f56_reproduction()
    # --- 4. availability on the analysis sample
    rec, u2, _ = E.build_records(E.DISC_FIRST, E.DISC_LAST)
    rec = rec[~rec.event.isin(excl)]
    out["availability"] = E.availability_block(rec)
    out["excluded_from_everything_(hourly_gap_gt_1.5)"] = excl
    (HERE / "checks.json").write_text(json.dumps(out, indent=1, default=str))

    L = ["# Research log #58 data checks (discovery dates %s .. %s)" % (E.DISC_FIRST, E.DISC_LAST), "",
         "Generated by checks.py. Games: %d regular-season 2025-26 events (events_list joined to #42's table)." % len(uni), ""]
    L += ["## T-4h early line, 1-minute table vs hourly table", "```", json.dumps({k: v for k, v in hsum.items() if k != "excluded_games"}, indent=1),
          "```", "Games more than 1.5 points apart (excluded from ALL results, both tables): %d" % len(excl)]
    L += ["- %s: 1m %.2f vs hourly %.2f" % (g["event"], g["L_1m"], g["L_hourly"]) for g in hsum["excluded_games"]]
    L += ["", "## Finals: hoopR vs Kalshi end-of-game (max expiration_value over NO-settled strikes) vs odds-API file", "```",
          json.dumps({k: v for k, v in out["finals"].items() if k != "odds_api_close_file"}, indent=1, default=str), "```",
          "Odds-API close file: %s" % json.dumps(out["finals"]["odds_api_close_file"]), "",
          "## F56 reproduction (our path vs #56 run_confirm path, all 2025-26 regular games)", "```",
          json.dumps(out["F56_reproduction_vs_56"], indent=1), "```", "",
          "## Book availability and spreads per t_e (analysis sample)", "```", json.dumps(out["availability"], indent=1), "```", "",
          "## Universe", "```", json.dumps(out["universe"], indent=1, default=str), "```"]
    (HERE / "CHECKS.md").write_text("\n".join(L))
    print(json.dumps({k: (v if k not in ("availability",) else "see checks.json") for k, v in out.items()}, indent=1, default=str)[:6000])


if __name__ == "__main__":
    main()
